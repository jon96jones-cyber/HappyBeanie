// Embeds the designed screener email — email-templates/waitlist/03-screener.html —
// as step 2 of the welcome sequence.
//
//   node tools/build-welcome-screener.js
//
// The design predates the sequence: it was drawn as part of the waitlist
// series, and it is a better screener email than a hand-written one — the
// hero photograph, and three real questions lifted from the screener itself.
// Only two lines tied it to the waitlist, and both are rewritten on the way
// through; everything else ships exactly as designed.
//
//   "Before Batch 0072 ships"        → "Before you order"
//   "asked for first dibs…"          → the sequence's own consent line
//   img/X                            → absolute URLs (recipients cannot read
//                                      relative paths; assets already live at
//                                      /assets/email from the waitlist set)
//   /screener                        → /quiz (the route that exists), + UTM
//   the unsubscribe link             → a per-recipient marker
//
// Re-run after any edit to the template, and commit both files.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'email-templates/waitlist/03-screener.html');
const OUT = path.join(ROOT, 'api/_lib/welcome-screener-email.js');
const SITE = 'https://www.happybeanie.com';
const UNSUB_MARK = '__HB_UNSUB__';

let html = fs.readFileSync(SRC, 'utf8');

const swaps = [
  ['Before Batch 0072 ships', 'Before you order'],
  ['you asked for first dibs at happybeanie.com', 'you signed up for emails from Happy Beanie'],
  [/src="img\/([^"]+)"/g, 'src="' + SITE + '/assets/email/$1"'],
  [/https:\/\/happybeanie\.com\/screener/g,
    SITE + '/quiz?utm_source=email&utm_medium=lifecycle&utm_campaign=welcome_2'],
  [/https:\/\/happybeanie\.com\/unsubscribe/g, UNSUB_MARK],
  // Anything else on the apex spends a redirect for nothing.
  [/https:\/\/happybeanie\.com/g, SITE]
];
swaps.forEach(function (s) {
  if (typeof s[0] === 'string' && html.indexOf(s[0]) === -1) {
    throw new Error('anchor not found in template: ' + s[0]);
  }
  html = html.replace(s[0], s[1]);
});

if (/src="img\//.test(html)) throw new Error('a relative image path survived');
if (/Batch 0072/i.test(html)) throw new Error('a batch reference survived');
if (html.indexOf(UNSUB_MARK) === -1) throw new Error('no unsubscribe link found to personalise');

fs.writeFileSync(OUT,
  '// GENERATED by tools/build-welcome-screener.js — do not edit.\n' +
  '//\n' +
  '// The design source is email-templates/waitlist/03-screener.html. Edit that,\n' +
  '// re-run the generator, and commit both. This is welcome step 2: the\n' +
  '// designed screener email, de-waitlisted. welcome-email.js swaps the\n' +
  '// UNSUB marker per recipient.\n' +
  '\n' +
  'module.exports = {\n' +
  '  UNSUB_MARK: ' + JSON.stringify(UNSUB_MARK) + ',\n' +
  '  html: ' + JSON.stringify(html) + '\n' +
  '};\n');
console.log('wrote', path.relative(ROOT, OUT), '·', Math.round(html.length / 1024) + 'KB');
