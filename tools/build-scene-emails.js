// Embeds the scene-style redesigns — email-templates/scene/ — as
// api/_lib/scene-designs.js.
//
//   node tools/build-scene-emails.js
//
// The scene set is the 2026-09 redesign: every email is one continuous
// world rather than a stack of banded sections, and the thing the email is
// about is drawn as an object (the offer as a box label, the cart as a
// receipt on a counter, the first month as a wall calendar, week one as
// seven chews counted out, the ambassador code as a lanyard pass).
//
// The HTML files are the design source and are never edited here. Embedding
// them in a module guarantees they ship inside the serverless bundle;
// reading from disk at runtime does not.
//
// Per-recipient values stay as markers, resolved by the builders:
//
//   __HB_UNSUB__     the unsubscribe link
//   __HB_CTA__       the campaign's call-to-action URL, with its UTM tags
//   __HB_CODEROW__   welcome step 1 only — the discount strip, shown only
//                    when the recipient actually holds a live code
//   {{ mustache }}   lifecycle's own variables, filled by lifecycle-email.js
//   [[TOKENS]]       ambassador's own variables, filled by ambassador-email.js
//
// Re-run after any template edit and commit both sides.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'email-templates/scene');
const OUT = path.join(ROOT, 'api/_lib/scene-designs.js');

const FILES = {
  welcomeCode: 'welcome-code.html',
  cartRecovery: 'cart-recovery.html',
  cartRow: 'cart-item-row.html',
  welcome1: 'welcome-1.html',
  ppCheckin: 'pp-checkin.html',
  research: 'research.html',
  ambassador: 'ambassador.html'
};

function read(name) {
  return fs.readFileSync(path.join(SRC, name), 'utf8');
}

const parts = Object.keys(FILES).map(function (key) {
  const html = read(FILES[key]);
  // A relative asset path is unreadable in an inbox — catch it here rather
  // than in someone's mail client.
  if (/(src|href)="\/(?!\/)/.test(html)) {
    throw new Error(FILES[key] + ' has a root-relative URL; use an absolute https URL');
  }
  return '  ' + key + ': ' + JSON.stringify(html);
});

const out = '// GENERATED by tools/build-scene-emails.js — do not edit.\n' +
  '// Source: email-templates/scene/*.html\n' +
  '//\n' +
  '// The scene-style email designs. Markers (__HB_UNSUB__, __HB_CTA__,\n' +
  '// __HB_CODEROW__) are resolved per recipient by the builders that use them.\n' +
  '\n' +
  'module.exports = {\n' +
  '  UNSUB_MARK: "__HB_UNSUB__",\n' +
  '  CTA_MARK: "__HB_CTA__",\n' +
  '  CODEROW_MARK: "__HB_CODEROW__",\n' +
  parts.join(',\n') + '\n' +
  '};\n';

fs.writeFileSync(OUT, out);
console.log('wrote ' + path.relative(ROOT, OUT) + ' — ' + Object.keys(FILES).length +
  ' designs, ' + out.length + ' bytes');
