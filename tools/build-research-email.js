// Embeds the designed research-pack email — email-templates/research/
// (the Setup_30 handoff) — as the html the research popup's signup receives.
//
//   node tools/build-research-email.js
//
// Per the handoff README: images move to /assets/email/lifecycle/ (the
// wordmark already lives there from Setup_27; the hero is flattened to JPEG
// and the chew downscaled to its 2x render size on the way in), and the
// unsubscribe link becomes a per-recipient marker. Everything else ships
// exactly as designed. research-email.js swaps the marker per recipient
// and keeps the subject and the plain-text alternate.
//
// Re-run after any edit to the template, and commit both files.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'email-templates/research/08researchpack.html');
const OUT = path.join(ROOT, 'api/_lib/research-designed.js');
const SITE = 'https://www.happybeanie.com';
const UNSUB_MARK = '__HB_UNSUB__';

let html = fs.readFileSync(SRC, 'utf8');

const swaps = [
  ['src="images/hb-wordmark.png"', 'src="' + SITE + '/assets/email/lifecycle/hb-wordmark.png"'],
  ['src="images/hero-dogs-cats.png"', 'src="' + SITE + '/assets/email/lifecycle/hero-dogs-cats.jpg"'],
  ['src="images/chew.png"', 'src="' + SITE + '/assets/email/lifecycle/chew.png"'],
  ['https://www.happybeanie.com/api/unsubscribe', UNSUB_MARK]
];
swaps.forEach(function (s) {
  if (html.indexOf(s[0]) === -1) throw new Error('anchor not found in template: ' + s[0]);
  html = html.replace(s[0], s[1]);
});

if (/src="images\//.test(html)) throw new Error('a relative image path survived');
if (/batch/i.test(html)) throw new Error('a batch reference survived');
if (html.indexOf(UNSUB_MARK) === -1) throw new Error('no unsubscribe link found to personalise');

fs.writeFileSync(OUT,
  '// GENERATED by tools/build-research-email.js — do not edit.\n' +
  '//\n' +
  '// The design source is email-templates/research/08researchpack.html\n' +
  '// (Setup_30). Edit that, re-run the generator, and commit both.\n' +
  '// research-email.js swaps the UNSUB marker per recipient.\n' +
  '\n' +
  'module.exports = {\n' +
  '  UNSUB_MARK: ' + JSON.stringify(UNSUB_MARK) + ',\n' +
  '  html: ' + JSON.stringify(html) + '\n' +
  '};\n');
console.log('wrote', path.relative(ROOT, OUT), '·', Math.round(html.length / 1024) + 'KB');
